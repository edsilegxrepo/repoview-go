// --- Template Embedding, Safety Errors & Renderer Setup ---

//go:embed templates/*
var defaultTemplates embed.FS

// ErrSafetyOverwrite indicates that an existing index.html lacks a RepoView signature.
type ErrSafetyOverwrite struct {
	Path string
}

func (e *ErrSafetyOverwrite) Error() string {
	return fmt.Sprintf("safety violation: %s already exists and was not generated by RepoView (use --force to overwrite)", e.Path)
}

func (e *ErrSafetyOverwrite) Unwrap() error {
	return models.ErrSafety
}

// Renderer compiles catalog HTML and aggregated RSS feeds.
type Renderer struct {
	tmpl *template.Template
}

// NewRenderer initializes a new portal Renderer with embedded or custom templates.
func NewRenderer(customTemplateDir string) (*Renderer, error) {
	funcMap := template.FuncMap{
		"upper": func(v interface{}) string {
			return strings.ToUpper(fmt.Sprint(v))
		},
		"lower": func(v interface{}) string {
			return strings.ToLower(fmt.Sprint(v))
		},
	}

	var t *template.Template
	if customTemplateDir != "" {
		pattern := filepath.Join(customTemplateDir, "*.html")
		var err error
		t, err = template.New("").Funcs(funcMap).ParseGlob(pattern)
		if err != nil {
			return nil, fmt.Errorf("%w: failed to parse custom templates: %w", models.ErrTemplate, err)
		}
	} else {
		var err error
		t, err = template.New("").Funcs(funcMap).ParseFS(defaultTemplates, "templates/*.html")
		if err != nil {
			return nil, fmt.Errorf("%w: failed to parse embedded portal templates: %w", models.ErrTemplate, err)
		}
	}

	return &Renderer{tmpl: t}, nil
}

// PortalContext passes state to portal.html.
type PortalContext struct {
	Catalog *Catalog
}

// RenderHTML executes portal.html template and returns HTML bytes.
func (r *Renderer) RenderHTML(catalog *Catalog) ([]byte, error) {
	if catalog == nil {
		return nil, fmt.Errorf("catalog cannot be nil")
	}

	var buf bytes.Buffer
	ctx := PortalContext{Catalog: catalog}

	if err := r.tmpl.ExecuteTemplate(&buf, "portal.html", ctx); err != nil {
		return nil, fmt.Errorf("failed to execute portal template: %w", err)
	}

	return buf.Bytes(), nil
}

// RSS XML Models for Aggregated Feed (Option C)

type rssFeed struct {
	XMLName xml.Name   `xml:"rss"`
	Version string     `xml:"version,attr"`
	Channel rssChannel `xml:"channel"`
}

type rssChannel struct {
	Title         string    `xml:"title"`
	Link          string    `xml:"link"`
	Description   string    `xml:"description"`
	Language      string    `xml:"language"`
	LastBuildDate string    `xml:"lastBuildDate"`
	Generator     string    `xml:"generator"`
	Items         []rssItem `xml:"item"`
}

type rssItem struct {
	Title       string `xml:"title"`
	Link        string `xml:"link"`
	Description string `xml:"description"`
	PubDate     string `xml:"pubDate"`
	GUID        string `xml:"guid"`
	date        time.Time
}

// RenderFeed compiles an aggregated RSS 2.0 feed merging latest child feeds and repository updates.
func (r *Renderer) RenderFeed(catalog *Catalog, rootDir string) ([]byte, error) {
	if catalog == nil {
		return nil, fmt.Errorf("catalog cannot be nil")
	}

	var allItems []rssItem
	now := time.Now().UTC()

	// 1. Collect repository update cards
	for _, repo := range catalog.Repos {
		targetLink := repo.TargetURL
		if catalog.BaseURL != "" && !strings.HasPrefix(targetLink, "http://") && !strings.HasPrefix(targetLink, "https://") {
			targetLink = strings.TrimSuffix(catalog.BaseURL, "/") + "/" + strings.TrimPrefix(targetLink, "/")
		}

		buildTime := repo.LastBuild
		if buildTime.IsZero() {
			buildTime = now
		}

		item := rssItem{
			Title:       fmt.Sprintf("[%s] %s (%s)", strings.ToUpper(repo.Distro), repo.Title, repo.Arch),
			Link:        targetLink,
			Description: fmt.Sprintf("Repository updated with %d packages. Format: %s, Channel/Components: %s", repo.PackageCount, strings.ToUpper(string(repo.Format)), repo.Channel),
			PubDate:     buildTime.Format(time.RFC1123Z),
			GUID:        targetLink + "#" + buildTime.Format("20060102150405"),
			date:        buildTime,
		}
		allItems = append(allItems, item)
	}

	// 2. Option C: Parallel aggregation of latest items from child repo latest-feed.xml
	if rootDir != "" {
		var candidateRepos []*DiscoveredRepo
		for _, repo := range catalog.Repos {
			if repo.IsRendered && repo.Path != "" {
				candidateRepos = append(candidateRepos, repo)
			}
		}

		if len(candidateRepos) > 0 {
			var itemsMu sync.Mutex
			util.ForEachConcurrent(candidateRepos, 0, func(_ int, repo *DiscoveredRepo) {
				items := r.readChildFeedItems(repo, rootDir, catalog.BaseURL)
				if len(items) > 0 {
					itemsMu.Lock()
					allItems = append(allItems, items...)
					itemsMu.Unlock()
				}
			})
		}
	}

	// Sort items descending by publication date
	sort.Slice(allItems, func(i, j int) bool {
		return allItems[i].date.After(allItems[j].date)
	})

	// Limit to top 50 entries
	if len(allItems) > 50 {
		allItems = allItems[:50]
	}

	channelLink := catalog.BaseURL
	if channelLink == "" {
		channelLink = "index.html"
	}

	feed := rssFeed{
		Version: "2.0",
		Channel: rssChannel{
			Title:         catalog.Title + " - Unified Feed",
			Link:          channelLink,
			Description:   catalog.Description,
			Language:      "en-us",
			LastBuildDate: now.Format(time.RFC1123Z),
			Generator:     "RepoView-Portal",
			Items:         allItems,
		},
	}

	var buf bytes.Buffer
	buf.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	enc := xml.NewEncoder(&buf)
	enc.Indent("", "  ")
	if err := enc.Encode(feed); err != nil {
		return nil, fmt.Errorf("failed to encode RSS XML: %w", err)
	}

	return buf.Bytes(), nil
}

// readChildFeedItems extracts up to 5 latest items from a child repo's latest-feed.xml.
func (r *Renderer) readChildFeedItems(repo *DiscoveredRepo, rootDir, portalBaseURL string) []rssItem {
	inSubdir := strings.HasPrefix(repo.TargetURL, "repoview/") || strings.Contains(repo.TargetURL, "/repoview/")
	var candidates []string
	if inSubdir {
		candidates = []string{
			filepath.Join(rootDir, repo.RelPath, "repoview", "latest-feed.xml"),
			filepath.Join(repo.Path, "repoview", "latest-feed.xml"),
			filepath.Join(rootDir, repo.RelPath, "latest-feed.xml"),
			filepath.Join(repo.Path, "latest-feed.xml"),
		}
	} else {
		candidates = []string{
			filepath.Join(rootDir, repo.RelPath, "latest-feed.xml"),
			filepath.Join(rootDir, repo.RelPath, "repoview", "latest-feed.xml"),
			filepath.Join(repo.Path, "repoview", "latest-feed.xml"),
			filepath.Join(repo.Path, "latest-feed.xml"),
		}
	}

	var feedPath string
	for _, c := range candidates {
		if fi, err := os.Stat(c); err == nil && !fi.IsDir() {
			feedPath = c
			break
		}
	}

	if feedPath == "" {
		return nil
	}

	const maxChildFeedBytes = 5 * 1024 * 1024 // 5 MiB ceiling per child RSS feed
	// #nosec G304 -- reading discovered child feed
	f, err := os.Open(filepath.Clean(feedPath))
	if err != nil {
		return nil
	}
	defer func() { _ = f.Close() }()

	data, err := io.ReadAll(io.LimitReader(f, maxChildFeedBytes))
	if err != nil {
		return nil
	}

	var parsed rssFeed
	if err := xml.Unmarshal(data, &parsed); err != nil {
		return nil
	}

	var items []rssItem
	limit := 5
	for i, it := range parsed.Channel.Items {
		if i >= limit {
			break
		}

		t, err := time.Parse(time.RFC1123Z, it.PubDate)
		if err != nil {
			t, err = time.Parse(time.RFC1123, it.PubDate)
			if err != nil {
				t = time.Now().UTC()
			}
		}

		itemLink := it.Link
		if !strings.HasPrefix(itemLink, "http://") && !strings.HasPrefix(itemLink, "https://") {
			// Resolve relative link from repo directory
			repoRel := strings.TrimPrefix(filepath.ToSlash(repo.RelPath), "./")
			if repoRel == "." {
				repoRel = ""
			}
			if inSubdir {
				if repoRel == "" {
					repoRel = "repoview"
				} else {
					repoRel += "/repoview"
				}
			}
			if repoRel != "" {
				itemLink = filepath.ToSlash(filepath.Join(repoRel, itemLink))
			} else {
				itemLink = filepath.ToSlash(filepath.Clean(itemLink))
			}
			if portalBaseURL != "" {
				itemLink = strings.TrimSuffix(portalBaseURL, "/") + "/" + strings.TrimPrefix(itemLink, "/")
			}
		}

		items = append(items, rssItem{
			Title:       fmt.Sprintf("[%s] %s", repo.Title, it.Title),
			Link:        itemLink,
			Description: it.Description,
			PubDate:     t.Format(time.RFC1123Z),
			GUID:        it.GUID,
			date:        t,
		})
	}

	return items
}

// WritePortal outputs index.html and portal-feed.xml into outputDir with overwrite safety and atomic rename.
func (r *Renderer) WritePortal(outputDir, rootDir string, catalog *Catalog, force bool) error {
	if catalog == nil {
		return fmt.Errorf("catalog cannot be nil")
	}

	cleanOut := filepath.Clean(outputDir)
	if err := util.EnsureDir(cleanOut); err != nil {
		return fmt.Errorf("%w: failed to create output directory %s: %w", models.ErrIO, cleanOut, err)
	}

	indexPath := filepath.Join(cleanOut, "index.html")

	// Overwrite Safety Guard (Option 2)
	if fi, err := os.Stat(indexPath); err == nil && !fi.IsDir() {
		if !force {
			// #nosec G304 -- inspecting pre-existing file for signature
			data, err := os.ReadFile(indexPath)
			if err == nil {
				content := string(data)
				if !strings.Contains(content, "RepoView-Portal") && !strings.Contains(content, `name="generator" content="RepoView"`) {
					return &ErrSafetyOverwrite{Path: indexPath}
				}
			}
		}
	}

	// Adjust relative target URLs if portal outputDir is different from rootDir
	absOut, errOut := filepath.Abs(cleanOut)
	absRoot, errRoot := filepath.Abs(rootDir)
	if errOut == nil && errRoot == nil && absOut != absRoot {
		for _, repo := range catalog.Repos {
			if repo.IsExternal || strings.HasPrefix(repo.TargetURL, "http://") || strings.HasPrefix(repo.TargetURL, "https://") {
				continue
			}
			// If already present directly inside absOut (detached output mode), no need to re-base against absRoot
			if _, err := os.Stat(filepath.Join(absOut, filepath.FromSlash(repo.TargetURL))); err == nil {
				continue
			}
			absTarget := filepath.Join(absRoot, repo.TargetURL)
			if rel, err := filepath.Rel(absOut, absTarget); err == nil {
				repo.TargetURL = filepath.ToSlash(rel)
			}
		}
	}

	// Render HTML
	htmlBytes, err := r.RenderHTML(catalog)
	if err != nil {
		return fmt.Errorf("%w: %w", models.ErrTemplate, err)
	}

	if err := util.AtomicWriteFile(indexPath, htmlBytes, util.DefaultFilePerm); err != nil {
		return fmt.Errorf("%w: failed to write index.html: %w", models.ErrIO, err)
	}

	// Render Feed
	feedBytes, err := r.RenderFeed(catalog, cleanOut)
	if err != nil {
		return fmt.Errorf("%w: %w", models.ErrTemplate, err)
	}

	feedPath := filepath.Join(cleanOut, "portal-feed.xml")
	if err := util.AtomicWriteFile(feedPath, feedBytes, util.DefaultFilePerm); err != nil {
		return fmt.Errorf("%w: failed to write portal-feed.xml: %w", models.ErrIO, err)
	}

	// Render aggregated cross-repository search index (portal-search.json)
	searchBytes, err := r.RenderPortalSearchIndex(catalog, cleanOut)
	if err != nil {
		return fmt.Errorf("%w: failed to build portal-search.json: %w", models.ErrIO, err)
	}
	searchPath := filepath.Join(cleanOut, "portal-search.json")
	if err := util.AtomicWriteFile(searchPath, searchBytes, util.DefaultFilePerm); err != nil {
		return fmt.Errorf("%w: failed to write portal-search.json: %w", models.ErrIO, err)
	}

	return nil
}

// PortalSearchRepo captures per-repository metadata referenced by portal-search.json rows.
type PortalSearchRepo struct {
	Title    string `json:"t"`
	BaseHref string `json:"h"`
	Distro   string `json:"d"`
	Format   string `json:"f"`
	Arch     string `json:"a"`
	Suite    string `json:"s,omitempty"`
}

// PortalSearchIndex aggregates child repository search.json entries for cross-repo browser search.
type PortalSearchIndex struct {
	Repos  []PortalSearchRepo `json:"repos"`
	Schema []string           `json:"schema"`
	Data   [][]string         `json:"data"`
}

// RenderPortalSearchIndex reads child search.json files and builds a compact portal-wide search index.
func (r *Renderer) RenderPortalSearchIndex(catalog *Catalog, outputDir string) ([]byte, error) {
	const maxChildSearchBytes = 16 * 1024 * 1024 // 16 MiB cap per child search.json

	idx := PortalSearchIndex{
		Schema: []string{"ri", "n", "v", "a", "s", "f", "l", "p", "c"},
		Repos:  make([]PortalSearchRepo, 0),
		Data:   make([][]string, 0),
	}
	if catalog == nil {
		return json.Marshal(idx)
	}

	for _, repo := range catalog.Repos {
		if repo == nil || !repo.IsRendered || repo.IsExternal {
			continue
		}

		// Locate child search.json safely inside outputDir or fallback repo.Path/repoview
		targetDirSlash := path.Dir(filepath.ToSlash(repo.TargetURL))
		if targetDirSlash == "." {
			targetDirSlash = ""
		}

		var candidates []string
		if outputDir != "" && !strings.HasPrefix(repo.TargetURL, "http://") && !strings.HasPrefix(repo.TargetURL, "https://") {
			if targetDirSlash != "" {
				candidates = append(candidates, filepath.Join(outputDir, filepath.FromSlash(targetDirSlash), "search.json"))
			} else {
				candidates = append(candidates, filepath.Join(outputDir, "search.json"))
			}
		}
		if repo.Path != "" {
			candidates = append(candidates,
				filepath.Join(repo.Path, "repoview", "search.json"),
				filepath.Join(repo.Path, "search.json"),
			)
		}

		var childBytes []byte
		for _, cand := range candidates {
			// #nosec G304 -- reading child search.json from validated portal output or discovered repo dir
			f, err := os.Open(filepath.Clean(cand))
			if err != nil {
				continue
			}
			data, readErr := io.ReadAll(io.LimitReader(f, maxChildSearchBytes))
			_ = f.Close()
			if readErr == nil && len(data) > 0 {
				childBytes = data
				break
			}
		}
		if len(childBytes) == 0 {
			continue
		}

		var child models.SearchIndex
		if err := json.Unmarshal(childBytes, &child); err != nil || len(child.Data) == 0 {
			continue
		}

		colIdx := make(map[string]int, len(child.Schema))
		for i, col := range child.Schema {
			colIdx[col] = i
		}
		getCol := func(row []string, key string) string {
			i, ok := colIdx[key]
			if !ok || i < 0 || i >= len(row) {
				return ""
			}
			return row[i]
		}

		repoIdx := fmt.Sprintf("%d", len(idx.Repos))
		idx.Repos = append(idx.Repos, PortalSearchRepo{
			Title:    repo.Title,
			BaseHref: targetDirSlash,
			Distro:   repo.Distro,
			Format:   string(repo.Format),
			Arch:     repo.Arch,
			Suite:    repo.Suite,
		})

		for _, row := range child.Data {
			name := getCol(row, "n")
			file := getCol(row, "f")
			if name == "" || file == "" {
				continue
			}
			idx.Data = append(idx.Data, []string{
				repoIdx,
				name,
				getCol(row, "v"),
				getCol(row, "a"),
				getCol(row, "s"),
				file,
				getCol(row, "l"),
				getCol(row, "p"),
				getCol(row, "t"),
			})
		}
	}

	return json.Marshal(idx)
}
